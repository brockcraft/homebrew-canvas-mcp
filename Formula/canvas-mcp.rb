  def install
    venv = virtualenv_create(libexec, "python3.13")
    venv.pip_install resources

    # The server is a single module, not a pip package, so install it by hand.
    libexec.install "server/canvas_mcp_server.py"

    # The skill is a Claude-app upload, not something the server reads at runtime.
    pkgshare.install "skill"

    (bin/"canvas-mcp").write <<~SH
      #!/bin/bash
      exec "#{libexec}/bin/python" "#{libexec}/canvas_mcp_server.py" "$@"
    SH
  end

  def caveats
    <<~EOS
      1. Store your Canvas token (input is hidden; use your own Canvas host):
           security add-generic-password -s canvas-api -a canvas.uw.edu -w
         On Linux, put it in ~/.canvas/token and run: chmod 600 ~/.canvas/token

      2. Add this to claude_desktop_config.json under "mcpServers"
         (for a host other than canvas.uw.edu, also add "env": { "CANVAS_HOST": "..." }):
           "canvas": { "command": "#{opt_bin}/canvas-mcp" }

      3. Upload the skill in Claude (Settings > Customize > Skills):
           #{opt_pkgshare}/skill/canvas-api/SKILL.md

      Then quit and reopen Claude.
    EOS
  end

  test do
    # The server speaks MCP over stdio; an initialize request must get a valid reply.
    init = '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2024-11-05",' \
           '"capabilities":{},"clientInfo":{"name":"brew-test","version":"0"}}}'
    output = pipe_output("#{bin}/canvas-mcp", "#{init}\n", 0)
    assert_match "canvas", output.downcase
    assert_path_exists pkgshare/"skill/canvas-api/SKILL.md"
  end
